
let a = 20;
let b = 5;

console.log("----- Arithmetic Operators -----");

console.log("Addition:", a + b);

console.log("Subtraction:", a - b);

console.log("Multiplication:", a * b);

console.log("Division:", a / b);

console.log("Modulus:", a % b);




console.log("----- Assignment Operators -----");

let x = 10;

x += 5;
console.log("After x += 5:", x);

x -= 3;
console.log("After x -= 3:", x);

x *= 2;
console.log("After x *= 2:", x);

x /= 4;
console.log("After x /= 4:", x);




console.log("----- Comparison Operators -----");

let p = 10;
let q = 20;

console.log("p == q:", p == q);

console.log("p != q:", p != q);

console.log("p === q:", p === q);

console.log("p < q:", p < q);

console.log("p > q:", p > q);

console.log("p <= q:", p <= q);

console.log("p >= q:", p >= q);



console.log("----- Logical Operators -----");

let hasID = true;
let hasTicket = true;
let isBanned = false;

// AND operator
console.log("AND:", hasID && hasTicket);

// OR operator
console.log("OR:", hasID || isBanned);

console.log("NOT:", !isBanned);




console.log("----- Increment Operator -----");

let count = 5;

console.log("Before Increment:", count);

count++;

console.log("After Increment:", count);



console.log("----- Decrement Operator -----");

let number = 5;

console.log("Before Decrement:", number);

number--;

console.log("After Decrement:", number);